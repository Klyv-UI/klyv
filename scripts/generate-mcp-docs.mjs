// Writes src/site/data/mcp.ts from the MCP server's own definitions.
//
// The page that documents the server imports this, so the two cannot disagree
// about which tools exist or what they take. Adding a tool to the server is
// enough to document it.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { RESOURCES, TOOLS } from '../mcp/server.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const data = (file) => JSON.parse(readFileSync(join(ROOT, 'data', file), 'utf8'))

const tools = TOOLS.map(({ name, description, inputSchema }) => ({
  name,
  description,
  args: Object.entries(inputSchema.properties ?? {}).map(([arg, schema]) => ({
    name: arg,
    type: schema.type ?? 'string',
    required: (inputSchema.required ?? []).includes(arg),
    description: schema.description ?? '',
  })),
}))

const resources = RESOURCES.map(({ uri, name, description, mimeType }) => ({
  uri,
  name,
  description,
  mimeType,
}))

// What the server actually knows, counted rather than claimed.
const props = data('props.json')
const tokens = data('tokens.json')
const facts = {
  components: Object.keys(data('components.json').catalog).length,
  props: Object.values(props).reduce((total, entry) => total + (entry.props?.length ?? 0), 0),
  tokens: ['color', 'radius', 'shadow', 'font'].reduce(
    (total, group) => total + Object.keys(tokens[group] ?? {}).length,
    0,
  ),
  darkOverrides: Object.keys(tokens.$modes?.dark?.color ?? {}).length,
}

const ts = `// GENERATED by scripts/generate-mcp-docs.mjs - do not edit.
//
// What the MCP server exposes, read off the server's own tool definitions.

export interface McpToolArg {
  name: string
  type: string
  required: boolean
  description: string
}

export interface McpTool {
  name: string
  description: string
  args: McpToolArg[]
}

export interface McpResource {
  uri: string
  name: string
  description: string
  mimeType: string
}

export const mcpTools: McpTool[] = ${JSON.stringify(tools, null, 2)}

export const mcpResources: McpResource[] = ${JSON.stringify(resources, null, 2)}

/** What the server can answer questions about, counted from the same data. */
export const mcpFacts = ${JSON.stringify(facts, null, 2)}
`

writeFileSync(join(ROOT, 'src', 'site', 'data', 'mcp.ts'), ts)
console.log(
  `mcp docs: ${tools.length} tools, ${resources.length} resources, ` +
    `${facts.props} props over ${facts.components} components`,
)
