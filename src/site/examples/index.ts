const cache = new Map<string, ExampleModule>()

/** The examples for one component, or undefined when its page is hand-written. */
export async function loadExamples(slug: string) {
  const owner = OWNER[slug]
  if (!owner) return undefined

  let module = cache.get(owner)
  if (!module) {
    module = (await MODULES[owner]()).demos
    cache.set(owner, module)
  }
  return module[slug]
}

